META_KEYS = {"name", "description", "tags", "examples"}


def main():
    for lang, data in L.items():
        d = ROOT / "locale" / lang
        d.mkdir(parents=True, exist_ok=True)
        for key, lines in data.items():
            if key in META_KEYS:
                continue
            (d / key).write_text("\n".join(lines) + "\n", encoding="utf-8")
        skill_json = {
            "skill_id": "ovos-skill-fart.andlo",
            "source": REPO,
            "package_name": "ovos-skill-fart",
            "pip_spec": "ovos-skill-fart",
            "license": "GPL-3.0-or-later",
            "author": "andlo",
            "name": data["name"],
            "description": data["description"],
            "examples": data["examples"],
            "tags": data["tags"],
            "icon": "https://raw.githubusercontent.com/andlo/ovos-skill-fart/main/icon.png",
        }
        (d / "skill.json").write_text(json.dumps(skill_json, indent=2, ensure_ascii=False) + "\n",
                                      encoding="utf-8")


if __name__ == "__main__":
    main()
